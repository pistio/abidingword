import type { TFunction } from "i18next";
import { referenceLabel } from "@/i18n/scripture";
import { sectionTitle } from "@/features/studies/builtinText";
import { findingLabel } from "@/features/studies/labels";
import type { DisplayLabel, DisplayLocation, SharedBlock } from "@/types/inquiry";

/** Localise generated locator words, never the source's own heading or printed label. */
export function inquiryLocation(t: TFunction, place: DisplayLocation): string {
  const parts = [place.section];
  if (place.firstPage) {
    parts.push(place.lastPage && place.lastPage !== place.firstPage
      ? t("studies.inquiry.location.pages", { first: place.firstPage, last: place.lastPage })
      : t("library.locator.page", { page: place.firstPage }));
  }
  parts.push(place.firstParagraph === place.lastParagraph
    ? t("studies.inquiry.location.paragraph", { number: place.firstParagraph })
    : t("studies.inquiry.location.paragraphs", { first: place.firstParagraph, last: place.lastParagraph }));
  return parts.filter(Boolean).join(t("common.listSeparator"));
}

/** Compose UI wording from typed facts, without splitting/parsing any user-authored label. */
export function inquiryDisplayLabel(t: TFunction, display: DisplayLabel): string {
  const join = (parts: (string | null)[]) => parts.filter(Boolean).join(t("common.listSeparator"));
  switch (display.type) {
    case "scripture":
      return referenceLabel(display.reference) + (display.translation ? ` (${display.translation})` : "");
    case "writing":
      return join([t(display.selected ? "scripture.selection.selectedWords" : "studies.inquiry.block.writing"), display.part ? sectionTitle(display.part) : null]);
    case "note":
      return join([`${t("studies.inquiry.block.note")} (${findingLabel(t, display.findingType)})`, display.part ? sectionTitle(display.part) : null, display.study]);
    case "quote":
      return join([t("studies.inquiry.block.quote"), display.citation, display.note]);
    case "source":
      return join([display.title, display.author, inquiryLocation(t, display.location)]);
    case "request":
      return t("studies.inquiry.block.request");
  }
}

/** Older test/extension payloads can omit metadata; production sends it for every block. */
export function inquiryBlockLabel(t: TFunction, block: SharedBlock): string {
  if (block.display) return inquiryDisplayLabel(t, block.display);
  if (block.kind === "scripture" && block.reference) return referenceLabel(block.reference) + (block.translation ? ` (${block.translation})` : "");
  return block.label;
}

/** This service label is generated by a known native prefix; model names stay byte-for-byte. */
export function inquiryAssistantLabel(t: TFunction, label: string): string {
  const other = "Other compatible service";
  return label === other || label.startsWith(`${other} · `)
    ? t("settings.assistant.providers.openai_compatible") + label.slice(other.length)
    : label;
}

/** Replace only the app-generated unavailable marker; installed Scripture stays exact. */
export function inquiryBlockText(t: TFunction, block: SharedBlock): string {
  return block.display?.type === "scripture" && !block.display.textAvailable
    ? t("presentation.export.labels.scriptureUnavailable") : block.text;
}
