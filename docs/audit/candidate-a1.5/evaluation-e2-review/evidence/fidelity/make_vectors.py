v("ES02","él -> el (composed)",s,s.replace("él","el"),"wrong")
v("ES03","él -> el, reference decomposed",D(s),s.replace("él","el"),"wrong")
v("ES04","ñ -> n",s,s.replace("niño","nino"),"wrong")
v("ES05","inverted question mark dropped",s,s[1:],"wrong")
v("ES06","acute -> grave",s,s.replace("irá","irà"),"wrong")
v("ES07","words merged 'que él irá' -> 'que élirá'",s,s.replace("él no irá","él noirá"),"wrong")
v("ES08","ñ as n + U+0303 (canonical)",s,s.replace("ñ","ñ"),"faithful")
v("ES09","ñ as n + spacing tilde U+02DC",s,s.replace("ñ","n˜"),"wrong")
# ---------------- Korean
k = "하나님이 빛을 보시니 좋았더라"
