#!/usr/bin/env python3
"""Reviewer's own adversarial fidelity vectors (independent review of A1.5-E2).
Every sentence is INVENTED for this review (not Scripture quotations, not the
author's golden vectors). `expect` is the reviewer's own judgement:
  faithful  - the texts are the same text (identical, canonically equivalent
              under Unicode, or differing only in the kind/amount of white space)
  wrong     - anything a reader could perceive as different text.
"""
import json, unicodedata as ud
N = lambda s: ud.normalize("NFC", s)
D = lambda s: ud.normalize("NFD", s)
V = []
def v(id, what, edition, found, expect, matched=False):
    V.append(dict(id=id, what=what, edition=edition, found=found, expect=expect, matched=matched))

# ---------------- English: word boundaries, punctuation, case
e = "The steward kept the lamps burning until the watchmen came home."
