v("EN02","words joined: 'watch men'->'watchmen' reversed",e.replace("watchmen","watch men"),e,"wrong")
v("EN03","words split",e,e.replace("until","un til"),"wrong")
v("EN04","case of one letter",e,e.replace("The steward","The Steward"),"wrong")
v("EN05","divine-name small caps vs title case","Then the LORD spoke to the steward.","Then the Lord spoke to the steward.","wrong")
v("EN06","possessive apostrophe dropped","the steward's lamp","the stewards lamp","wrong")
v("EN07","straight vs curly apostrophe","the steward’s lamp","the steward's lamp","wrong")
v("EN08","comma moved","Truly, I say to you today you will see","Truly I say to you, today you will see","wrong")
v("EN09","full stop to question mark","You are the steward.","You are the steward?","wrong")
v("EN10","em dash vs en dash","lamps—burning","lamps–burning","wrong")
v("EN11","hyphen removed (word boundary)","burnt-offering","burnt offering","wrong")
v("EN12","double space",e,e.replace(" kept","  kept"),"faithful")
v("EN13","NBSP for space",e,e.replace(" kept"," kept"),"faithful")
v("EN14","tab and newline inside",e,e.replace(" kept","\t\nkept"),"faithful")
v("EN15","trailing and leading white space incl. U+3000",e,"　 "+e+" ","faithful")
v("EN16","inserted negation",e,e.replace("kept","never kept"),"wrong")
v("EN17","digit for number word","forty lamps","40 lamps","wrong")
v("EN18","one letter changed",e,e.replace("lamps","lambs"),"wrong")
v("EN19","note sign appended",e,e+"*","wrong")
v("EN20","pilcrow prefix",e,"¶ "+e,"wrong")
v("EN21","editorial brackets dropped","[the steward wept]","the steward wept","wrong")
v("EN22","verse number leaked at start",e,"14 "+e,"wrong")
v("EN23","next verse's opening leaked at end",e,e+" 15 And the watchmen","wrong")
v("EN24","last clause missing",e,"The steward kept the lamps burning","wrong")
v("EN25","citation appended",e,e+" (Lamps 3:4)","wrong")
v("EN26","footnote caller letter appended",e,e.replace("burning","burningᵃ"),"wrong")
v("EN27","footnote caller plain letter",e,e.replace("burning","burninga"),"wrong")
v("EN28","U+2028 line separator inside",e,e.replace(" until"," until"),"faithful")
v("EN29","U+0085 NEL inside",e,e.replace(" until","\u0085until"),"faithful")
v("EN30","dotless i",e,e.replace("until","untıl"),"wrong")
v("EN31","Cyrillic homoglyph a",e,e.replace("lamps","lаmps"),"wrong")
v("EN32","Greek omicron homoglyph",e,e.replace("home","hοme"),"wrong")
# ---------------- German
g = "Und der Hüter sprach: Größer ist die Treue als das Brot."
v("DE01","composed vs decomposed umlaut and eszett text",g,D(g),"faithful")
v("DE02","umlaut lost",g,g.replace("Hüter","Huter"),"wrong")
v("DE03","umlaut as ue",g,g.replace("Hüter","Hueter"),"wrong")
v("DE04","ß to ss",g,g.replace("Größer","Grösser"),"wrong")
v("DE05","capital sharp s",g.upper(),g.upper().replace("SS","ẞ"),"wrong")
v("DE06","noun capitalisation",g,g.replace("Treue","treue"),"wrong")
v("DE07","German quotes vs English quotes","„Wacht!“","“Wacht!”","wrong")
v("DE08","colon spacing removed (French-style)",g,g.replace("sprach:","sprach :"),"wrong")
v("DE09","combining diaeresis on wrong base",g,g.replace("Hüter","Hüter".replace("ü","u")+"̈"),"wrong")
# ---------------- Spanish
s = "¿Quién dirá que él no irá con el niño a la mañana?"
