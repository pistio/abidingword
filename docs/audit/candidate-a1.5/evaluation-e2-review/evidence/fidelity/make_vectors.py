v("GR06","oxia U+1F79 vs tonos U+03CC (canonical singleton)",gk,gk.replace("θεόν","θεόν"),"faithful")
v("GR07","ano teleia U+0387 vs middle dot U+00B7 (canonical)",gk,gk.replace("·","·"),"faithful")
v("GR08","Greek question mark U+037E vs semicolon (canonical)","τίς ἐστιν;","τίς ἐστιν;","faithful")
v("GR09","final sigma -> medial sigma",gk,gk.replace("λόγος,","λόγοσ,"),"wrong")
v("GR10","grave -> acute",gk,gk.replace("πρὸς","πρός"),"wrong")
v("GR11","diaeresis lost","Ἠσαΐας","Ἠσαιας","wrong")
v("GR12","mark order breathing/accent swapped (decomposed)","ἄ","ά̓","wrong")
v("GR13","koronis U+1FBD vs apostrophe","κἀγώ","κ᾽ἀγώ","wrong")
v("GR14","ypogegrammeni spacing U+037A vs combining U+0345","ᾳ","αͺ","wrong")
v("GR15","capitalised article",gk,gk.replace("ὁ λόγος,","Ὁ λόγος,"),"wrong")
v("GR16","accents stripped entirely",gk,"".join(c for c in D(gk) if not ud.combining(c)),"wrong")
v("GR17","combining tone marks U+0340/U+0341 vs U+0300/U+0301 (canonical)","ά","ά","faithful")
v("GR18","dialytika-tonos U+0344 vs U+0308 U+0301 (canonical)","ΐ","ΐ","faithful")
v("GR19","Greek beta symbol U+03D0 (compatibility)","βίβλος","ϐίβλος","wrong")
# ---------------- Hebrew
h = "בְּרֵאשִׁית בָּרָא אֱלֹהִים"
v("HE01","identical NFD",h,D(h),"faithful")
v("HE02","dagesh/vowel order permuted (canonical reorder)","בָּ","בָּ","faithful")
v("HE03","pointed vs unpointed",h,"בראשית ברא אלהים","wrong")
v("HE04","shin dot -> sin dot",h,h.replace("ׁ","ׂ"),"wrong")
v("HE05","cantillation lost","בָּרָ֣א","בָּרָא","wrong")
v("HE06","cantillation changed","בָּרָ֣א","בָּרָ֖א","wrong")
