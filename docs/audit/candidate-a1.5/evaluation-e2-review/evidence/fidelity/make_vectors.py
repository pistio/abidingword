v("KO02","compatibility jamo spelling",k,k.replace("빛","ㅂㅣㅊ"),"wrong")
v("KO03","word spacing removed",k,k.replace("하나님이 빛을","하나님이빛을"),"wrong")
v("KO04","word spacing added",k,k.replace("하나님이","하나님 이"),"wrong")
