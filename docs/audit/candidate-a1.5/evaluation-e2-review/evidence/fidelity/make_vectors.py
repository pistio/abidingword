v("KO06","final consonant (batchim) changed",k,k.replace("빛","빗"),"wrong")
v("KO07","Hangul to Hanja",k,k.replace("하나님","上帝"),"wrong")
v("KO08","CJK compatibility ideograph U+F914 vs U+6A02 (canonical singleton)","樂","樂","faithful")
v("KO09","half-width Hangul (compatibility)",k,k.replace("하","ﾾￂ"),"wrong")
v("KO10","jamo mixing composed+decomposed per syllable",k,"하"+D("나")+"님이 빛을 보시니 좋았더라","faithful")
v("KO11","old Hangul arae-a jamo sequence vs composed modern",D("ᄒᆞ나님"),"ᄒᆞ나님","faithful")
v("KO12","old Hangul arae-a vs modern a",("ᄒᆞ나님"),"하나님","wrong")
v("KO13","middle dot U+00B7 vs U+318D arae-a compat","ㆍ","·","wrong")
# ---------------- Greek polytonic
gk = "ἐν ἀρχῇ ἦν ὁ λόγος, καὶ ὁ λόγος ἦν πρὸς τὸν θεόν·"
